(function () {
  GameEvents.Subscribe('game_rules_state_change', function () {
    if (Game.GameStateIsBefore(DOTA_GameState.DOTA_GAMERULES_STATE_PRE_GAME)) return;
    SwapInGameIcons();
    SwapSpectatorIcons();
    SwapChatIcons();
  });

  LoopSwapPreGameIcons();
  LoopSwapInGameIcons();
  LoopSwapSpectatorIcons();
  LoopSwapChatIcons();
})();
